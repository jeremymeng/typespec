pub fn is_keyword(token: Token) -> bool {
    (token as u32) >= Token::ImportKeyword as u32
        && (token as u32) < Token::StatemachineKeyword as u32
}

pub fn is_reserved_keyword(token: Token) -> bool {
    (token as u32) >= Token::StatemachineKeyword as u32 && (token as u32) < TOKEN_COUNT
}

pub fn is_punctuation(token: Token) -> bool {
    (token as u32) >= Token::OpenBrace as u32 && (token as u32) <= Token::EqualsGreaterThan as u32
}

pub fn is_statement_keyword(token: Token) -> bool {
    (token as u32) >= Token::ImportKeyword as u32 && (token as u32) < Token::ExternKeyword as u32
}

